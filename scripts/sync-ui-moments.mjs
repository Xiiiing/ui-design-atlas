// Derive single-control entries from the pinned, unmodified UI Moments pages.
// Extraction follows upstream tools/build-original-cards.mjs (MIT).
// Copyright (c) 2026 guanmo-ai; see examples/ui-market/licenses/ui-moments-LICENSE.
import { readFile, writeFile } from "node:fs/promises";
import { runInNewContext } from "node:vm";
import assert from "node:assert/strict";

const base = new URL(
  "../examples/ui-market/public/ui-moments/",
  import.meta.url,
);
const read = (file) => readFile(new URL(file, base), "utf8");
const context = { window: {} };
runInNewContext(await read("upstream/gallery/works.js"), context);
const resources = JSON.parse(
  await readFile(new URL("../content/resources.json", import.meta.url)),
);
const aliases = { odometer: "odometer-stepper", checklist: "stroke-checklist" };
const pages = new Map();
let count = 0;
for (const resource of resources.filter((r) =>
  r.id.startsWith("ui-moments-"),
)) {
  const slug = resource.id.replace("ui-moments-", "");
  const work = context.window.WORKS.find(
    (item) => item.id === (aliases[slug] || slug),
  );
  if (!work) continue;
  const path = work.demo.split("#")[0];
  if (!pages.has(path)) pages.set(path, await read("upstream/" + path));
  const source = pages.get(path).replaceAll("\r\n", "\n");
  const samples = [
    ...source.matchAll(
      /<section class="sample" id="([^"]+)"[\s\S]*?<\/section>/g,
    ),
  ];
  const sample = samples.find((match) => match[1] === work.id);
  assert.ok(sample, work.id);
  const script = [...source.matchAll(/<script>([\s\S]*?)<\/script>/g)].at(
    -1,
  )[1];
  const themeEnd = script.indexOf(
    "\n    });",
    script.indexOf("$('#theme').addEventListener"),
  );
  assert.ok(themeEnd > 0, path);
  const behavior = script.slice(themeEnd + "\n    });".length);
  const blocks = [...behavior.matchAll(/^    \{\n([\s\S]*?)^    \}/gm)];
  const scripted = samples.filter((match) => match[1] !== "stroke-checklist");
  assert.equal(blocks.length, scripted.length, path);
  let code =
    work.id === "stroke-checklist"
      ? ""
      : behavior.slice(0, blocks[0].index) +
        blocks[scripted.indexOf(sample)][0];
  // An aborted drag must never commit an action, even beyond the threshold.
  if (work.id === "swipe-confirm") {
    const before =
      "if (Number(track.style.getPropertyValue('--x')) > max() * .88) confirm(); else set(0);";
    assert.ok(code.includes(before));
    code = code.replace(
      before,
      "if (event.type === 'pointerup' && Number(track.style.getPropertyValue('--x')) > max() * .88) confirm(); else set(0);",
    );
  }
  const css = source
    .match(/<style>([\s\S]*?)<\/style>/)[1]
    .replaceAll("../../assets/", "../upstream/assets/");
  const helpers = script
    .slice(0, script.indexOf("    // One control per view:"))
    .replace(
      "matchMedia('(prefers-reduced-motion: reduce)')",
      "window.atlasUI.motion",
    );
  const html = `<!doctype html>
<!-- Derived from guanmo-ai/ui-moments, cd49fd207d9333d3c442ffdbf39a9b3b055d358f, ${path}#${work.id}.
Copyright (c) 2026 guanmo-ai. MIT; see ../upstream/LICENSE.
Generated by scripts/sync-ui-moments.mjs; Atlas framing and protocol in shared/upstream.js. -->
<html lang="en" data-embedded="true"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${work.en} · UI Moments</title><link rel="icon" href="data:,">
<style>${css}</style><link rel="stylesheet" href="../shared/upstream.css">
</head><body data-resource="${resource.id}" data-demo="${slug}" data-upstream="${work.id}">
<main id="root"><header><h1 data-en="${work.en}" data-zh="${work.title}">${work.en}</h1><a href="../upstream/LICENSE">guanmo-ai · MIT</a></header>
<div id="stage"><div id="demo">${sample[0]}</div></div>
<footer><button id="pause" type="button" aria-pressed="false">Pause motion</button></footer></main>
<script src="../shared/upstream.js"></script>
<script>(() => {
const requestAnimationFrame = window.atlasUI.requestFrame;
const cancelAnimationFrame = window.atlasUI.cancelFrame;
const performance = window.atlasUI.performance;
${helpers}
${code}
window.atlasUI.ready();
})();</script></body></html>
`;
  const target = new URL(`${slug}/index.html`, base);
  if (process.argv.includes("--check"))
    assert.equal(
      await readFile(target, "utf8"),
      html,
      `${slug}: run node scripts/sync-ui-moments.mjs`,
    );
  else await writeFile(target, html);
  count++;
}
assert.equal(count, 23);
console.log(
  `${process.argv.includes("--check") ? "Verified" : "Generated"} ${count} entries from pinned UI Moments originals.`,
);
